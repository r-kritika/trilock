"""SYNTHETIC fingerprint-like images for tests and demos.

These are generated by iterative oriented Gabor filtering of noise (a simplified take on the
SFinGe idea). They are NOT real fingerprints. Results measured on them say something about the
plumbing and the matcher's geometry handling, never about real-world fingerprint accuracy.
`finger(seed)` is one identity; `impression(seed, k)` is a repeat capture of that identity with
random rotation / shift / partial crop / noise.
"""
from __future__ import annotations

from functools import lru_cache

import cv2
import numpy as np

SIZE = 320


def _orientation_field(rng: np.random.Generator, n: int) -> np.ndarray:
    y, x = np.mgrid[0:n, 0:n].astype(np.float32)
    cx, cy = rng.uniform(0.4, 0.6, 2) * n
    dx, dy = rng.uniform(-0.3, 0.3, 2) * n
    # loop-like field: half-angle around a core and a delta
    core = 0.5 * np.arctan2(y - cy, x - cx)
    delta = -0.5 * np.arctan2(y - (cy + 0.35 * n + dy), x - (cx + dx))
    return (core + delta + rng.uniform(0, np.pi)) % np.pi


@lru_cache(maxsize=256)
def finger(seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = SIZE
    theta = _orientation_field(rng, n)
    freq = rng.uniform(0.09, 0.12)
    img = rng.standard_normal((n, n)).astype(np.float32)
    n_or = 16
    bank = []
    for k in range(n_or):
        a = k * np.pi / n_or
        kern = cv2.getGaborKernel((21, 21), 4.0, a + np.pi / 2, 1.0 / freq, 0.6, 0)
        bank.append(kern)
    idx = np.round(theta / np.pi * n_or).astype(int) % n_or
    for _ in range(6):
        stack = np.stack([cv2.filter2D(img, -1, k) for k in bank])
        img = np.take_along_axis(stack, idx[None], axis=0)[0]
        img = (img - img.mean()) / (img.std() + 1e-6)
    out = cv2.normalize(img, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    # Oval fingertip mask on a light background. Size, tilt and centre differ per identity: with one
    # shared outline every pair of prints would share boundary keypoints, which inflates impostor
    # matches (a confound found while auditing the evaluation).
    mask = np.zeros((n, n), np.uint8)
    centre = (int(n / 2 + rng.uniform(-0.04, 0.04) * n), int(n / 2 + rng.uniform(-0.04, 0.04) * n))
    axes = (int(n * rng.uniform(0.32, 0.42)), int(n * rng.uniform(0.40, 0.49)))
    cv2.ellipse(mask, centre, axes, rng.uniform(-15, 15), 0, 360, 255, -1)
    bg = np.full_like(out, 235)
    out = np.where(mask > 0, out, bg)
    out.flags.writeable = False     # cached; callers must copy before modifying
    return out


def impression(seed: int, k: int, noise: float = 6.0) -> np.ndarray:
    """k-th repeat capture of finger `seed` (deterministic)."""
    rng = np.random.default_rng(10_000 * seed + k + 1)
    base = finger(seed)
    ang = rng.uniform(-15, 15)
    tx, ty = rng.uniform(-18, 18, 2)
    M = cv2.getRotationMatrix2D((SIZE / 2, SIZE / 2), ang, rng.uniform(0.95, 1.05))
    M[:, 2] += (tx, ty)
    out = cv2.warpAffine(base, M, (SIZE, SIZE), borderValue=235)
    out = out.astype(np.float32) * rng.uniform(0.85, 1.1) + rng.normal(0, noise, out.shape)
    return np.clip(out, 0, 255).astype(np.uint8)


def to_png(img: np.ndarray) -> bytes:
    ok, buf = cv2.imencode(".png", img)
    assert ok
    return buf.tobytes()
